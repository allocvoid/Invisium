//! Browser state that does not depend on the window: tabs, navigation, history, and applying
//! network results to pages.

use crate::internal::{self, Info, Internal};
use crate::loader::{self, NetEvent, Sink};
use crate::settings::Settings;
use invis_chrome::{ChromeState, Security, TabInfo, TorIndicator};
use invisium::draw::ImageId;
use invisium::page::{decode_text, Page, PageAction, PageConfig};
use invisium::paint::PaintImage;
use invisium::text::FontSystem;
use invisium_net::{NetService, RequestHandle, TorStatus, Url};
use std::time::{Duration, Instant};

pub struct LivePage {
    pub page: Page,
    pub nav: u64,
    /// The document was generated by the browser itself (an `invis://` page or an error page),
    /// not received from the network. Only such pages may link to `invis://` addresses.
    pub internal: bool,
}

pub struct Tab {
    pub id: u64,
    pub title: String,
    pub url: String,
    /// Latest navigation generation; results from older ones are ignored.
    pub nav: u64,
    pub page: Option<LivePage>,
    /// The next page, held back briefly until its stylesheets arrive (avoids an unstyled flash).
    pub incoming: Option<(LivePage, Instant)>,
    pub history: Vec<String>,
    pub pos: usize,
    pub blocked: u32,
    pub zoom: f32,
    handles: Vec<RequestHandle>,
    doc_pending: bool,
    outstanding: u32,
    /// When this tab's scripts last ran while it was in the background.
    last_script_run: f64,
}

impl Tab {
    pub fn loading(&self) -> bool {
        self.doc_pending || self.incoming.is_some() || self.outstanding > 0
    }
}

pub struct Browser {
    pub settings: Settings,
    pub net: std::sync::Arc<NetService>,
    pub sink: Sink,
    /// Shared with every page (scripts can force layout). Never hold a borrow of it across a
    /// page call that can run script.
    pub fonts: std::rc::Rc<std::cell::RefCell<FontSystem>>,
    pub tabs: Vec<Tab>,
    pub active: usize,
    /// Page viewport in CSS pixels (set by the window before pages are created).
    pub viewport: (f32, f32),
    /// GPU images no longer referenced by any page; the window releases them.
    pub dropped_images: Vec<ImageId>,
    pub gpu_info: String,
    pub status: Option<String>,
    next_tab: u64,
    next_nav: u64,
    started: Instant,
    /// Print page console output to stderr (`INVIS_JS_CONSOLE=1`).
    js_console: bool,
}

fn page_origin(lp: &LivePage) -> String {
    if lp.internal {
        "invis://internal".to_string()
    } else {
        lp.page.url.clone()
    }
}

fn short_title(url: &str) -> String {
    if let Some(rest) = url.strip_prefix("invis://") {
        let name = rest.split(['?', '/']).next().unwrap_or("");
        return match name {
            "" | "newtab" => "New tab".into(),
            "settings" => "Settings".into(),
            "about" => "About InvisBrowser".into(),
            other => other.to_string(),
        };
    }
    match Url::parse(url) {
        Ok(u) if !u.host().is_empty() => u.host().to_string(),
        _ => url.chars().take(60).collect(),
    }
}

impl Browser {
    pub fn new(sink: Sink) -> Browser {
        let settings = Settings::load();
        let net = std::sync::Arc::new(NetService::new(settings.net_config()));
        let mut fonts = FontSystem::new();
        crate::headless::register_fonts(&mut fonts);
        Browser {
            settings,
            net,
            sink,
            fonts: std::rc::Rc::new(std::cell::RefCell::new(fonts)),
            tabs: Vec::new(),
            active: 0,
            viewport: (1200.0, 700.0),
            dropped_images: Vec::new(),
            gpu_info: String::new(),
            status: None,
            next_tab: 1,
            next_nav: 1,
            started: Instant::now(),
            js_console: std::env::var_os("INVIS_JS_CONSOLE").is_some(),
        }
    }

    fn now_ms(&self) -> f64 {
        self.started.elapsed().as_secs_f64() * 1000.0
    }

    pub fn index_of(&self, id: u64) -> Option<usize> {
        self.tabs.iter().position(|t| t.id == id)
    }

    pub fn new_tab(&mut self, url: &str) -> usize {
        let id = self.next_tab;
        self.next_tab += 1;
        self.tabs.push(Tab {
            id,
            title: "New tab".into(),
            url: String::new(),
            nav: 0,
            page: None,
            incoming: None,
            history: Vec::new(),
            pos: 0,
            blocked: 0,
            zoom: 1.0,
            handles: Vec::new(),
            doc_pending: false,
            outstanding: 0,
            last_script_run: 0.0,
        });
        let idx = self.tabs.len() - 1;
        self.navigate(idx, url, true, None);
        idx
    }

    /// Close a tab. Returns false when it was the last one.
    pub fn close_tab(&mut self, id: u64) -> bool {
        let Some(idx) = self.index_of(id) else { return true };
        let tab = self.tabs.remove(idx);
        for h in &tab.handles {
            h.cancel();
        }
        for lp in tab.page.iter().chain(tab.incoming.iter().map(|i| &i.0)) {
            self.dropped_images.extend(lp.page.image_ids());
        }
        if self.tabs.is_empty() {
            return false;
        }
        if self.active > idx || self.active >= self.tabs.len() {
            self.active = self.active.saturating_sub(1).min(self.tabs.len() - 1);
        }
        true
    }

    pub fn select_tab(&mut self, id: u64) {
        let Some(idx) = self.index_of(id) else { return };
        if idx == self.active {
            return;
        }
        // the tab we are leaving gives back everything that can be rebuilt
        if self.settings.hibernate_tabs {
            if let Some(lp) = self.tabs[self.active].page.as_mut() {
                lp.page.hibernate();
            }
        }
        self.active = idx;
        self.status = None;
    }

    fn cancel_loads(&mut self, idx: usize) {
        let tab = &mut self.tabs[idx];
        for h in tab.handles.drain(..) {
            h.cancel();
        }
        tab.outstanding = 0;
        tab.doc_pending = false;
        if let Some((lp, _)) = tab.incoming.take() {
            self.dropped_images.extend(lp.page.image_ids());
        }
    }

    /// Go to `input` (an address, search terms, or an `invis://` page).
    pub fn navigate(&mut self, idx: usize, input: &str, push: bool, body: Option<Vec<u8>>) {
        let mut url = loader::fix_url(input, &self.settings.search);
        self.cancel_loads(idx);
        let nav = self.next_nav;
        self.next_nav += 1;
        self.tabs[idx].nav = nav;
        self.tabs[idx].blocked = 0;

        // internal pages resolve immediately (possibly redirecting to a real address)
        let mut hops = 0;
        let mut settings_changed = false;
        let internal_html = loop {
            if !url.starts_with("invis:") {
                break None;
            }
            let info = self.info();
            match internal::handle(&url, &mut self.settings, &info) {
                Internal::Html(h) => break Some(h),
                Internal::Redirect { url: u, settings_changed: c } => {
                    settings_changed |= c;
                    url = u;
                    hops += 1;
                    if hops > 5 {
                        break Some(invis_chrome::pages::error("Redirect loop", "An internal page kept redirecting.", &url, None));
                    }
                }
            }
        };
        if settings_changed {
            self.apply_settings();
        }

        let tab = &mut self.tabs[idx];
        if push {
            // settings actions replace the current entry instead of piling up history
            let replace = settings_changed && tab.history.get(tab.pos).map_or(false, |h| h == &url);
            if !replace {
                tab.history.truncate(tab.pos + if tab.history.is_empty() { 0 } else { 1 });
                tab.history.push(url.clone());
                tab.pos = tab.history.len() - 1;
            }
        }
        tab.url = url.clone();
        if let Some(html) = internal_html {
            self.install(idx, nav, url, &html, true);
            self.promote(idx, true);
            return;
        }
        match Url::parse(&url) {
            Ok(parsed) => {
                let referrer = None; // typed and link navigations start clean; the policy layer adds what is allowed
                let h = loader::fetch_document(&self.net, &self.sink, self.tabs[idx].id, nav, parsed, body, referrer);
                let tab = &mut self.tabs[idx];
                tab.handles.push(h);
                tab.doc_pending = true;
            }
            Err(e) => {
                let html = loader::error_html(&invisium_net::NetError::InvalidUrl(format!("{e:?}")), &url);
                self.install(idx, nav, url, &html, true);
                self.promote(idx, true);
            }
        }
    }

    /// A navigation asked for by page content (a link, a form, a script) of the page at `from`.
    /// Returns the tab the navigation went to, or `None` if it was refused.
    pub fn navigate_from_page(&mut self, idx: usize, from: &str, url: &str, body: Option<Vec<u8>>, new_tab: bool) -> Option<usize> {
        if !loader::page_may_open(from, url) {
            self.status = Some("Blocked: a web page tried to open an internal browser page".into());
            return None;
        }
        if new_tab {
            Some(self.new_tab(url))
        } else {
            self.navigate(idx, url, true, body);
            Some(idx)
        }
    }

    /// Who is asking when the page a tab is showing navigates: the page's address, or an
    /// `invis:` address if the browser generated that document itself.
    pub fn shown_url(&self, idx: usize) -> String {
        self.tabs.get(idx).and_then(|t| t.page.as_ref()).map(page_origin).unwrap_or_default()
    }

    pub fn back(&mut self, idx: usize) {
        let tab = &mut self.tabs[idx];
        if tab.pos > 0 {
            tab.pos -= 1;
            let url = tab.history[tab.pos].clone();
            self.navigate(idx, &url, false, None);
        }
    }

    pub fn forward(&mut self, idx: usize) {
        let tab = &mut self.tabs[idx];
        if tab.pos + 1 < tab.history.len() {
            tab.pos += 1;
            let url = tab.history[tab.pos].clone();
            self.navigate(idx, &url, false, None);
        }
    }

    pub fn reload(&mut self, idx: usize) {
        let url = self.tabs[idx].url.clone();
        if !url.is_empty() {
            self.navigate(idx, &url, false, None);
        }
    }

    pub fn stop(&mut self, idx: usize) {
        self.cancel_loads(idx);
    }

    fn install(&mut self, idx: usize, nav: u64, url: String, html: &str, internal: bool) {
        // the browser's own pages never run script
        let scripting = self.settings.javascript && !internal;
        let cfg = PageConfig { dark: !self.settings.light_scheme_only, load_images: self.settings.load_images, scripting };
        let mut page = Page::new(&url, html, loader::url_join(), self.viewport, cfg);
        if scripting {
            page.set_cookie_access(loader::cookie_access(self.net.clone()));
            page.set_fonts(self.fonts.clone());
            page.set_script_stack(crate::loader::SCRIPT_STACK);
        }
        let tab = &mut self.tabs[idx];
        tab.url = url;
        if let Some(h) = tab.history.get_mut(tab.pos) {
            *h = tab.url.clone();
        }
        tab.incoming = Some((LivePage { page, nav, internal }, Instant::now()));
        self.pump(idx);
        // inline scripts run before the first paint
        let now = self.now_ms();
        self.run_scripts(idx, now, true);
        self.promote(idx, false);
    }

    /// Show the incoming page once its stylesheets are in (or it has waited long enough).
    fn promote(&mut self, idx: usize, force: bool) -> bool {
        let tab = &mut self.tabs[idx];
        let ready = match &tab.incoming {
            Some((lp, since)) => force || lp.page.pending_stylesheets() == 0 || since.elapsed() > Duration::from_millis(1200),
            None => false,
        };
        if !ready {
            return false;
        }
        let (lp, _) = tab.incoming.take().unwrap();
        if let Some(old) = tab.page.take() {
            self.dropped_images.extend(old.page.image_ids());
        }
        tab.title = if lp.page.title.is_empty() { short_title(&tab.url) } else { lp.page.title.clone() };
        tab.page = Some(lp);
        true
    }

    /// Start any fetches the tab's pages have asked for.
    pub fn pump(&mut self, idx: usize) {
        let Browser { net, sink, tabs, .. } = self;
        let tab = &mut tabs[idx];
        let id = tab.id;
        let mut new = Vec::new();
        if let Some((lp, _)) = tab.incoming.as_mut() {
            new.extend(loader::fetch_subresources(net, sink, id, lp.nav, &mut lp.page));
        }
        if let Some(lp) = tab.page.as_mut() {
            new.extend(loader::fetch_subresources(net, sink, id, lp.nav, &mut lp.page));
        }
        tab.outstanding += new.len() as u32;
        tab.handles.extend(new);
    }

    fn page_for(&mut self, idx: usize, nav: u64) -> Option<&mut Page> {
        let tab = &mut self.tabs[idx];
        if let Some((lp, _)) = tab.incoming.as_mut() {
            if lp.nav == nav {
                return Some(&mut lp.page);
            }
        }
        match tab.page.as_mut() {
            Some(lp) if lp.nav == nav => Some(&mut lp.page),
            _ => None,
        }
    }

    /// Apply one network result. `upload` turns decoded pixels into a GPU image.
    pub fn on_net(&mut self, ev: NetEvent, upload: &mut dyn FnMut(u32, u32, &[u8]) -> ImageId) {
        match ev {
            NetEvent::Document { tab, nav, result } => {
                let Some(idx) = self.index_of(tab) else { return };
                if self.tabs[idx].nav != nav {
                    return;
                }
                self.tabs[idx].doc_pending = false;
                match result {
                    Ok(resp) => {
                        let url = resp.url.as_str().to_string();
                        let html = loader::document_html(&resp);
                        self.install(idx, nav, url, &html, false);
                    }
                    Err(e) => {
                        let url = self.tabs[idx].url.clone();
                        let html = loader::error_html(&e, &url);
                        self.install(idx, nav, url, &html, true);
                        self.promote(idx, true);
                    }
                }
            }
            NetEvent::Sheet { tab, nav, req, result } => {
                let Some(idx) = self.index_of(tab) else { return };
                self.tabs[idx].outstanding = self.tabs[idx].outstanding.saturating_sub(1);
                let mut blocked = false;
                if let Some(page) = self.page_for(idx, nav) {
                    match result {
                        Ok(resp) if resp.status < 400 => page.stylesheet_loaded(req, &decode_text(&resp.body, resp.charset.as_deref())),
                        Ok(_) => page.resource_failed(req),
                        Err(e) => {
                            blocked = loader::is_blocked(&e);
                            page.resource_failed(req);
                        }
                    }
                }
                if blocked {
                    self.tabs[idx].blocked += 1;
                }
                self.pump(idx);
                self.promote(idx, false);
            }
            NetEvent::Script { tab, nav, req, result } => {
                let Some(idx) = self.index_of(tab) else { return };
                self.tabs[idx].outstanding = self.tabs[idx].outstanding.saturating_sub(1);
                let mut blocked = false;
                if let Some(page) = self.page_for(idx, nav) {
                    match result {
                        Ok(resp) if resp.status < 400 => page.script_loaded(req, &decode_text(&resp.body, resp.charset.as_deref())),
                        Ok(_) => page.resource_failed(req),
                        Err(e) => {
                            blocked = loader::is_blocked(&e);
                            page.resource_failed(req);
                        }
                    }
                }
                if blocked {
                    self.tabs[idx].blocked += 1;
                }
                let now = self.now_ms();
                self.run_scripts(idx, now, true);
                self.promote(idx, false);
            }
            NetEvent::Fetch { tab, nav, id, result } => {
                let Some(idx) = self.index_of(tab) else { return };
                self.tabs[idx].outstanding = self.tabs[idx].outstanding.saturating_sub(1);
                if let Some(page) = self.page_for(idx, nav) {
                    page.fetch_done(id, loader::fetch_result(result));
                }
                let now = self.now_ms();
                self.run_scripts(idx, now, true);
            }
            NetEvent::Image { tab, nav, url, result } => {
                let Some(idx) = self.index_of(tab) else { return };
                self.tabs[idx].outstanding = self.tabs[idx].outstanding.saturating_sub(1);
                match result {
                    Ok(img) => {
                        if self.page_for(idx, nav).is_some() {
                            let id = upload(img.width, img.height, &img.rgba);
                            if let Some(page) = self.page_for(idx, nav) {
                                page.image_ready(&url, PaintImage { id, width: img.orig_w as f32, height: img.orig_h as f32 });
                            }
                        }
                    }
                    Err(e) => {
                        if loader::is_blocked(&e) {
                            self.tabs[idx].blocked += 1;
                        }
                    }
                }
            }
        }
    }

    /// Periodic work. Returns true if something visible changed.
    pub fn tick(&mut self) -> bool {
        let mut changed = false;
        let now = self.now_ms();
        for idx in 0..self.tabs.len() {
            changed |= self.promote(idx, false);
            changed |= self.run_scripts(idx, now, false);
        }
        changed
    }

    /// Let a tab's pages run the script work that is due (scripts that arrived, timers), start
    /// the fetches they asked for and follow navigations they requested. Background tabs are
    /// throttled to once a second unless `force` is set. Returns true if anything ran.
    fn run_scripts(&mut self, idx: usize, now: f64, force: bool) -> bool {
        let active = idx == self.active;
        let print = self.js_console;
        let tab = &mut self.tabs[idx];
        if !active && !force && now - tab.last_script_run < 1000.0 {
            return false;
        }
        tab.last_script_run = now;
        let mut ran = false;
        let mut action = None;
        let pages = tab.incoming.iter_mut().map(|(lp, _)| &mut lp.page).chain(tab.page.iter_mut().map(|lp| &mut lp.page));
        for page in pages {
            for _ in 0..4 {
                if !page.pump(now) {
                    break;
                }
                ran = true;
            }
            if let Some(a) = page.take_action() {
                // only network documents run script, so the page's own address is the asker
                action = Some((a, page.url.clone()));
            }
            for m in page.take_console() {
                if print {
                    eprintln!("[js] {}", m.text);
                }
            }
        }
        if ran {
            if let Some(lp) = self.tabs[idx].page.as_ref() {
                if !lp.page.title.is_empty() {
                    self.tabs[idx].title = lp.page.title.clone();
                }
            }
            self.pump(idx);
        }
        match action {
            Some((PageAction::Navigate { url, .. }, from)) => {
                self.navigate_from_page(idx, &from, &url, None, false);
            }
            Some((PageAction::Submit { url, body }, from)) => {
                self.navigate_from_page(idx, &from, &url, body, false);
            }
            _ => {}
        }
        ran
    }

    /// Milliseconds until the visible page's next script timer, if it has one.
    pub fn next_script_wake(&self) -> Option<u64> {
        let now = self.now_ms();
        let tab = self.tabs.get(self.active)?;
        let due = tab.page.as_ref()?.page.next_timer_ms()?;
        Some((due - now).max(0.0).ceil() as u64)
    }

    pub fn apply_settings(&mut self) {
        self.net.set_config(self.settings.net_config());
        let dark = !self.settings.light_scheme_only;
        for tab in &mut self.tabs {
            if let Some(lp) = tab.page.as_mut() {
                lp.page.set_dark(dark);
            }
        }
    }

    pub fn active_page(&mut self) -> Option<&mut Page> {
        self.tabs.get_mut(self.active).and_then(|t| t.page.as_mut()).map(|lp| &mut lp.page)
    }

    fn security(&self, url: &str) -> Security {
        if url.starts_with("invis:") || url.is_empty() {
            return Security::Internal;
        }
        match Url::parse(url) {
            Ok(u) if u.host().ends_with(".onion") => Security::Onion,
            Ok(_) if self.settings.uses_tor() => Security::Tor,
            Ok(u) if u.is_secure() => Security::Secure,
            _ => Security::Insecure,
        }
    }

    pub fn chrome_state(&self) -> ChromeState {
        let tor = if self.settings.uses_tor() {
            match self.net.tor_status() {
                TorStatus::Ready => TorIndicator::On,
                TorStatus::Bootstrapping { percent, .. } => TorIndicator::Connecting(percent),
                TorStatus::Failed(_) => TorIndicator::Failed,
                TorStatus::Off => TorIndicator::Connecting(0),
            }
        } else {
            TorIndicator::Off
        };
        let active = self.tabs.get(self.active);
        ChromeState {
            tabs: self
                .tabs
                .iter()
                .map(|t| TabInfo { id: t.id, title: t.title.clone(), url: t.url.clone(), loading: t.loading(), security: self.security(&t.url), blocked: t.blocked })
                .collect(),
            active: self.active,
            can_back: active.map_or(false, |t| t.pos > 0),
            can_forward: active.map_or(false, |t| t.pos + 1 < t.history.len()),
            tor,
            toggles: self.settings.toggles(),
            status: self.status.clone(),
            progress: active.filter(|t| t.loading()).map(|t| if t.doc_pending { 0.2 } else if t.incoming.is_some() { 0.6 } else { 0.85 }),
            zoom_percent: active.map_or(100, |t| (t.zoom * 100.0).round() as u32),
        }
    }

    /// Facts for the about and new-tab pages.
    pub fn info(&self) -> Info {
        let n = self.net.stats();
        let (faces, mapped) = self.fonts.borrow().stats();
        let mut rows = vec![
            ("Browser".to_string(), format!("InvisBrowser {}", env!("CARGO_PKG_VERSION"))),
            ("Engine".to_string(), "Invisium (HTML, CSS, layout, paint, networking: written from scratch)".to_string()),
            ("Graphics".to_string(), if self.gpu_info.is_empty() { "not started".to_string() } else { self.gpu_info.clone() }),
            ("Open tabs".to_string(), self.tabs.len().to_string()),
            ("Requests this session".to_string(), format!("{} sent, {} blocked", n.requests, n.blocked)),
            ("Data received".to_string(), format!("{} KB", n.bytes_received / 1024)),
            ("Memory cache".to_string(), format!("{} KB", n.cache_bytes / 1024)),
            ("Cookies held (memory only)".to_string(), n.cookies.to_string()),
            ("Fonts".to_string(), format!("{} faces, {} KB memory-mapped", faces, mapped / 1024)),
        ];
        if let Some(lp) = self.tabs.get(self.active).and_then(|t| t.page.as_ref()) {
            let m = lp.page.memory();
            rows.push((
                "This tab".to_string(),
                format!(
                    "{} nodes, {} boxes, {} shared styles; DOM {} KB, styles {} KB, layout {} KB, display list {} KB",
                    m.nodes,
                    m.boxes,
                    m.unique_styles,
                    m.dom / 1024,
                    m.styles / 1024,
                    m.layout / 1024,
                    m.display_list / 1024
                ),
            ));
        }
        let stats = vec![
            ("Trackers blocked".to_string(), n.blocked.to_string()),
            ("Requests sent".to_string(), n.requests.to_string()),
            ("Open tabs".to_string(), self.tabs.len().to_string()),
        ];
        Info { rows, stats }
    }
}
