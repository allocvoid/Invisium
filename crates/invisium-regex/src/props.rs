//! `\p{…}` property sets. These are approximations built from the standard library's `char`
//! predicates and from block ranges; exact Unicode tables are a non-goal of this crate.

use crate::charset::{CharSet, MAX_CODE_POINT};
use std::sync::OnceLock;

type Ranges = &'static [(u32, u32)];

/// The set for the text between the braces of `\p{…}`, or `None` if it is not supported.
pub(crate) fn lookup(spec: &str) -> Option<CharSet> {
    match spec.split_once('=') {
        Some((name, value)) => match name {
            "General_Category" | "gc" => general_category(value),
            "Script" | "sc" | "Script_Extensions" | "scx" => script(value).map(CharSet::from_ranges),
            _ => None,
        },
        None => general_category(spec).or_else(|| binary_property(spec)),
    }
}

fn general_category(name: &str) -> Option<CharSet> {
    Some(match name {
        "L" | "Letter" => cached(Pred::Letter),
        "Lu" | "Uppercase_Letter" => cached(Pred::UpperLetter),
        "Ll" | "Lowercase_Letter" => cached(Pred::LowerLetter),
        "Lt" | "Titlecase_Letter" => CharSet::from_ranges(TITLECASE),
        "N" | "Number" => cached(Pred::Numeric),
        "Nd" | "Decimal_Number" | "digit" => decimal_digits(),
        "P" | "Punctuation" | "punct" => CharSet::from_ranges(PUNCTUATION),
        "S" | "Symbol" => CharSet::from_ranges(SYMBOL),
        "Z" | "Separator" => {
            let mut set = CharSet::from_ranges(SPACE_SEPARATOR);
            set.add_range(0x2028, 0x2029);
            set.normalize();
            set
        }
        "Zs" | "Space_Separator" => CharSet::from_ranges(SPACE_SEPARATOR),
        _ => return None,
    })
}

fn binary_property(name: &str) -> Option<CharSet> {
    Some(match name {
        "Alphabetic" | "Alpha" => cached(Pred::Alphabetic),
        "White_Space" | "space" => cached(Pred::WhiteSpace),
        "Uppercase" | "Upper" => cached(Pred::Uppercase),
        "Lowercase" | "Lower" => cached(Pred::Lowercase),
        "ASCII" => CharSet::from_ranges(&[(0, 0x7F)]),
        "Any" => CharSet::from_ranges(&[(0, MAX_CODE_POINT)]),
        _ => return None,
    })
}

#[derive(Clone, Copy)]
enum Pred {
    Letter,
    UpperLetter,
    LowerLetter,
    Numeric,
    Alphabetic,
    WhiteSpace,
    Uppercase,
    Lowercase,
}

/// Predicate-based sets need a scan of the whole code space, so each is built once.
fn cached(pred: Pred) -> CharSet {
    static CACHE: [OnceLock<CharSet>; 8] = [
        OnceLock::new(),
        OnceLock::new(),
        OnceLock::new(),
        OnceLock::new(),
        OnceLock::new(),
        OnceLock::new(),
        OnceLock::new(),
        OnceLock::new(),
    ];
    let test: fn(char) -> bool = match pred {
        Pred::Letter => |c| c.is_alphabetic() && !c.is_numeric(),
        Pred::UpperLetter => |c| c.is_uppercase() && c.is_alphabetic() && !c.is_numeric(),
        Pred::LowerLetter => |c| c.is_lowercase() && c.is_alphabetic() && !c.is_numeric(),
        Pred::Numeric => char::is_numeric,
        Pred::Alphabetic => char::is_alphabetic,
        Pred::WhiteSpace => char::is_whitespace,
        Pred::Uppercase => char::is_uppercase,
        Pred::Lowercase => char::is_lowercase,
    };
    match CACHE.get(pred as usize) {
        Some(cell) => cell.get_or_init(|| from_predicate(test)).clone(),
        None => from_predicate(test),
    }
}

fn from_predicate(test: fn(char) -> bool) -> CharSet {
    let mut set = CharSet::new();
    let mut start: Option<u32> = None;
    for c in 0..=MAX_CODE_POINT {
        let hit = char::from_u32(c).is_some_and(test);
        match (hit, start) {
            (true, None) => start = Some(c),
            (false, Some(s)) => {
                set.add_range(s, c - 1);
                start = None;
            }
            _ => {}
        }
    }
    if let Some(s) = start {
        set.add_range(s, MAX_CODE_POINT);
    }
    set
}

fn decimal_digits() -> CharSet {
    let mut set = CharSet::new();
    for &start in DIGIT_RUNS {
        set.add_range(start, start + 9);
    }
    set.add_range(0x1D7CE, 0x1D7FF); // mathematical digits
    set.normalize();
    set
}

