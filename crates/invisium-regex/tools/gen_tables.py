"""Generate src/gc_table.rs: the General_Category of every code point.

Run from the project root with the Python that ships Unicode 15.0.0 in `unicodedata`:

    py -3.12 crates/invisium-regex/tools/gen_tables.py

The output is deterministic: running the script twice gives a byte-identical file.
"""

import os
import sys
import unicodedata

# Leaf categories. The index of a name is the low byte of its table entries.
CATEGORIES = [
    "Lu", "Ll", "Lt", "Lm", "Lo",
    "Mn", "Mc", "Me",
    "Nd", "Nl", "No",
    "Pc", "Pd", "Ps", "Pe", "Pi", "Pf", "Po",
    "Sm", "Sc", "Sk", "So",
    "Zs", "Zl", "Zp",
    "Cc", "Cf", "Cs", "Co", "Cn",
]

MAX_CODE_POINT = 0x10FFFF
PER_LINE = 8


def runs():
    """(start, category index) for every maximal run of one category."""
    index = {name: i for i, name in enumerate(CATEGORIES)}
    out = []
    previous = None
    for cp in range(MAX_CODE_POINT + 1):
        cat = index[unicodedata.category(chr(cp))]
        if cat != previous:
            out.append((cp, cat))
            previous = cat
    return out


def render(entries):
    lines = [
        "// @generated by crates/invisium-regex/tools/gen_tables.py -- do not edit by hand.",
        "// Command: py -3.12 crates/invisium-regex/tools/gen_tables.py",
        "// Unicode version: %s (Python unicodedata)." % unicodedata.unidata_version,
        "//",
        "// General_Category of every code point. Each entry is `start << 8 | category`, where",
        "// `category` indexes CATEGORY_NAMES; a run ends where the next entry starts, and the",
        "// last run ends at U+10FFFF. Sorted by start; neighbouring entries differ in category.",
        "",
        "pub(crate) const CATEGORY_NAMES: [&str; %d] = [" % len(CATEGORIES),
    ]
    for i in range(0, len(CATEGORIES), 10):
        chunk = CATEGORIES[i:i + 10]
        lines.append("    " + " ".join('"%s",' % name for name in chunk))
    lines.append("];")
    lines.append("")
    lines.append("pub(crate) static GC_TABLE: [u32; %d] = [" % len(entries))
    for i in range(0, len(entries), PER_LINE):
        chunk = entries[i:i + PER_LINE]
        lines.append("    " + " ".join("0x%08X," % (start << 8 | cat) for start, cat in chunk))
    lines.append("];")
    return "\n".join(lines) + "\n"


def main():
    if unicodedata.unidata_version != "15.0.0":
        sys.exit("expected Unicode 15.0.0, this Python has %s; run with py -3.12"
                 % unicodedata.unidata_version)
    here = os.path.dirname(os.path.abspath(__file__))
    target = os.path.join(here, "..", "src", "gc_table.rs")
    text = render(runs())
    with open(target, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote %s" % os.path.normpath(target))


if __name__ == "__main__":
    main()
