//! Annex B leniency without `u`, each case next to its Unicode-mode twin, which must be a
//! `SyntaxError`.

use crate::common::{Case, ERR, NO};

pub const CASES: &[Case] = &[
    // `{` and `}` are literals when they do not form a quantifier.
    ("a{", "", "a{", 0, "0,2"),
    ("a{", "u", "", 0, ERR),
    ("{", "", "{", 0, "0,1"),
    ("{", "u", "", 0, ERR),
    ("a{1", "", "a{1", 0, "0,3"),
    ("a{1", "u", "", 0, ERR),
    ("a{1,", "", "a{1,", 0, "0,4"),
    ("a{1,", "u", "", 0, ERR),
    ("a{,2}", "", "a{,2}", 0, "0,5"),
    ("a{,2}", "u", "", 0, ERR),
    ("x{a}", "", "x{a}", 0, "0,4"),
    ("x{a}", "u", "", 0, ERR),
    ("x{2,}{", "", "xx{", 0, "0,3"),
    ("x{2,}{", "u", "", 0, ERR),
    ("}", "", "}", 0, "0,1"),
    ("}", "u", "", 0, ERR),
    ("a}", "", "a}", 0, "0,2"),
    ("a}", "u", "", 0, ERR),
    // A braced quantifier with nothing to repeat is an error in both modes.
    ("{1}", "", "", 0, ERR),
    ("{1}", "u", "", 0, ERR),
    ("a|{2,3}", "", "", 0, ERR),
    // `]` is a literal.
    ("]", "", "]", 0, "0,1"),
    ("]", "u", "", 0, ERR),
    ("a]b", "", "a]b", 0, "0,3"),
    ("a]b", "u", "", 0, ERR),
    // Legacy octal escapes; `\N` is a backreference only when group N exists.
    (r"\1", "", "\u{1}", 0, "0,1"),
    (r"\07", "", "\u{7}", 0, "0,1"),
    (r"\07", "u", "", 0, ERR),
    (r"\101", "", "A", 0, "0,1"),
    (r"\101", "u", "", 0, ERR),
    (r"\377", "", "\u{ff}", 0, "0,1"),
    (r"\400", "", " 0", 0, "0,2"),
    (r"\10", "", "\u{8}", 0, "0,1"),
    (r"(a)\10", "", "a\u{8}", 0, "0,2 0,1"),
    (r"(a)\2", "", "a\u{2}", 0, "0,2 0,1"),
    (r"\00", "", "\0", 0, "0,1"),
    (r"\00", "u", "", 0, ERR),
    (r"\01", "", "\u{1}", 0, "0,1"),
    (r"\01", "u", "", 0, ERR),
    (r"\08", "", "\u{0}8", 0, "0,2"),
    (r"\08", "u", "", 0, ERR),
    (r"\8", "", "8", 0, "0,1"),
    (r"\8", "u", "", 0, ERR),
    (r"\9", "", "9", 0, "0,1"),
    (r"\9", "u", "", 0, ERR),
    (r"[\1]", "", "\u{1}", 0, "0,1"),
    (r"[\1]", "u", "", 0, ERR),
    (r"[\12]", "", "\n", 0, "0,1"),
    // Identity escapes of characters that need no escaping.
    (r"\a", "", "a", 0, "0,1"),
    (r"\a", "u", "", 0, ERR),
    (r"\-", "", "-", 0, "0,1"),
    (r"\-", "u", "", 0, ERR),
    (r"[\-]", "u", "-", 0, "0,1"),
    (r"\ ", "", " ", 0, "0,1"),
    (r"\ ", "u", "", 0, ERR),
    (r"\@\_\z\e\g", "", "@_zeg", 0, "0,5"),
    (r"\@", "u", "", 0, ERR),
    (r"\_", "u", "", 0, ERR),
    ("\\\u{e9}", "", "\u{e9}", 0, "0,1"),
    ("\\\u{e9}", "u", "", 0, ERR),
    (r"[\B]", "", "B", 0, "0,1"),
    (r"[\B]", "u", "", 0, ERR),
    // `\c` before a non-letter is a literal backslash.
    (r"\c", "", "\\c", 0, "0,2"),
    (r"\c", "u", "", 0, ERR),
    (r"\c1", "", "\\c1", 0, "0,3"),
    (r"\c1", "u", "", 0, ERR),
    (r"[\c]+", "", "c\\", 0, "0,2"),
    (r"[\c]", "u", "", 0, ERR),
    (r"[\c1]", "", "\u{11}", 0, "0,1"),
    (r"[\c1]", "u", "", 0, ERR),
    (r"[\c_]", "", "\u{1f}", 0, "0,1"),
    (r"[\c_]", "u", "", 0, ERR),
    // Incomplete `\x` and `\u` are the letters themselves.
    (r"\x", "", "x", 0, "0,1"),
    (r"\x", "u", "", 0, ERR),
    (r"\x4", "", "x4", 0, "0,2"),
    (r"\x4", "u", "", 0, ERR),
    (r"\u", "", "u", 0, "0,1"),
    (r"\u", "u", "", 0, ERR),
    (r"\u12", "", "u12", 0, "0,3"),
    (r"\u12", "u", "", 0, ERR),
    (r"\u{2}", "", "uu", 0, "0,2"),
    (r"\u{2}", "u", "\u{2}", 0, "0,1"),
    (r"[\x]", "", "x", 0, "0,1"),
    (r"[\u]", "u", "", 0, ERR),
    // `\k` is an identity escape when the pattern has no named group.
    (r"\k", "", "k", 0, "0,1"),
    (r"\k", "u", "", 0, ERR),
    (r"\k<a>", "", "k<a>", 0, "0,4"),
    (r"\k<a>", "u", "", 0, ERR),
    (r"[\k]", "", "k", 0, "0,1"),
    (r"[\k]", "u", "", 0, ERR),
    (r"(?<a>.)[\k]", "", "", 0, ERR),
    // A lookahead may be quantified; a lookbehind may not.
    ("(?=a)*a", "", "a", 0, "0,1"),
    ("(?=a)*a", "u", "", 0, ERR),
    ("(?!a)+b", "", "b", 0, "0,1"),
    ("(?!a)+b", "u", "", 0, ERR),
    ("(?=a){2}a", "", "a", 0, "0,1"),
    ("(?=a){2}a", "u", "", 0, ERR),
    ("(?=(a))?b", "", "b", 0, "0,1 -"),
    ("(?=(a))*a", "", "a", 0, "0,1 -"),
    ("(?=(a))+a", "", "a", 0, "0,1 0,1"),
    ("(?=a)?b", "", "ab", 0, "1,2"),
    ("(?<=a)?b", "", "", 0, ERR),
    // A class escape beside `-` makes the dash a literal.
    (r"[\d-z]+", "", "1-z", 0, "0,3"),
    (r"[\d-z]", "u", "", 0, ERR),
    (r"[a-\d]+", "", "a-5", 0, "0,3"),
    (r"[a-\d]", "u", "", 0, ERR),
    (r"[\w-\s]+", "", "a- ", 0, "0,3"),
    (r"[\w-\s]", "u", "", 0, ERR),
    (r"[\d-z]", "", "b", 0, NO),
];
