//! ECMAScript-specific matching semantics: capture reset in loops, empty iterations,
//! backreferences and lookarounds.

use crate::common::{Case, ERR, NO};

pub const CASES: &[Case] = &[
    // Captures inside a quantified group are unset at the start of every iteration.
    ("(?:(a)|b)+", "", "ab", 0, "0,2 -"),
    ("(?:(a)|b)*", "", "ab", 0, "0,2 -"),
    ("(?:(a)|(b))+", "", "ab", 0, "0,2 - 1,2"),
    ("(?:(a)|(b))+", "", "ba", 0, "0,2 1,2 -"),
    ("((a)|(b))*", "", "aab", 0, "0,3 2,3 - 2,3"),
    ("(?:(a)|(b)|(c))+", "", "abc", 0, "0,3 - - 2,3"),
    ("(z)((a+)?(b+)?(c))*", "", "zaacbbbcac", 0, "0,10 0,1 8,10 8,9 - 9,10"),
    ("((a)|b){2}", "", "ab", 0, "0,2 1,2 -"),
    ("(?:(a)|b){2,}", "", "ab", 0, "0,2 -"),
    ("(?:(a)|b){1,5}?$", "", "ab", 0, "0,2 -"),
    ("(?:(a)|b)+?$", "", "ab", 0, "0,2 -"),
    ("(a|b)*", "", "ab", 0, "0,2 1,2"),
    ("(a+)*b", "", "aaab", 0, "0,4 0,3"),
    ("(a)?(b)?", "", "b", 0, "0,1 - 0,1"),
    ("(?:(\\w)\\1)+", "", "aabbc", 0, "0,4 2,3"),
    // An optional iteration that matches the empty string ends the loop.
    ("(a*)*", "", "b", 0, "0,0 -"),
    ("(a*)+", "", "b", 0, "0,0 0,0"),
    ("(a*)?", "", "b", 0, "0,0 -"),
    ("(a*)*", "", "aab", 0, "0,2 0,2"),
    ("(a?)*", "", "aa", 0, "0,2 1,2"),
    ("(?:a*)*b", "", "aaab", 0, "0,4"),
    ("(?:a*)+$", "", "aa", 0, "0,2"),
    ("(?:)*", "", "a", 0, "0,0"),
    ("(?:)+", "", "a", 0, "0,0"),
    ("()*", "", "a", 0, "0,0 -"),
    ("()+", "", "a", 0, "0,0 0,0"),
    ("()??", "", "a", 0, "0,0 -"),
    ("(?:|a)*", "", "aa", 0, "0,2"),
    ("(?:|a)+", "", "aa", 0, "0,2"),
    ("(?:a|)*b", "", "aab", 0, "0,3"),
    ("(?:^)*a", "", "a", 0, "0,1"),
    (r"(\b)*a", "", "a", 0, "0,1 -"),
    // Mandatory iterations may be empty; optional ones may not.
    ("(?:){3}", "", "a", 0, "0,0"),
    ("(?:a?){3}", "", "aa", 0, "0,2"),
    ("(a?){3}", "", "aa", 0, "0,2 2,2"),
    ("(a?){2,3}", "", "aa", 0, "0,2 1,2"),
    ("(a*){2}", "", "aa", 0, "0,2 2,2"),
    // Backreferences.
    (r"(a)\1", "", "aa", 0, "0,2 0,1"),
    (r"(a)\1", "", "ab", 0, NO),
    (r"(a)?\1b", "", "b", 0, "0,1 -"),
    (r"\1(a)", "", "a", 0, "0,1 0,1"),
    (r"(a\1)", "", "aa", 0, "0,1 0,1"),
    (r"(?:(a)|b)\1", "", "b", 0, "0,1 -"),
    (r"(a)|\1b", "", "b", 0, "0,1 -"),
    (r"(a*)b\1", "", "aabaa", 0, "0,5 0,2"),
    (r"(a*)b\1", "", "aaba", 0, "1,4 1,2"),
    (r"(.)(.)\2\1", "", "xabba", 0, "1,5 1,2 2,3"),
    (r#"(?<q>['"]).*?\k<q>"#, "", "say 'hi' \"x\"", 0, "4,8 4,5"),
    (r"\k<a>(?<a>x)", "", "x", 0, "0,1 0,1"),
    (r"(?<a>a)\k<a>", "", "aa", 0, "0,2 0,1"),
    (r"(?<a>a)\k<b>", "", "", 0, ERR),
    (r"(?<a>a)\k", "", "", 0, ERR),
    (r"(?<a>a)\k<a", "", "", 0, ERR),
    (r"(a)\2", "u", "", 0, ERR),
    (r"\1", "u", "", 0, ERR),
    // Lookahead.
    ("a(?=b)", "", "acab", 0, "2,3"),
    ("a(?!b)", "", "abac", 0, "2,3"),
    ("(?=(a))a", "", "a", 0, "0,1 0,1"),
    (r"(?=(a+))a*b\1", "", "baaabac", 0, "3,6 3,4"),
    (r"(.*?)a(?!(a+)b\2c)\2(.*)", "", "baaabaac", 0, "0,8 0,2 - 3,8"),
    ("(?!(a)b)a", "", "ac", 0, "0,1 -"),
    ("(?=(?=(a)))a", "", "a", 0, "0,1 0,1"),
    ("(?=(a)(?!b))", "", "ab ac", 0, "3,3 3,4"),
    ("(?=(a+))", "", "baaa", 0, "1,1 1,4"),
    ("(?=(a|ab))ab", "", "ab", 0, "0,2 0,1"),
    ("(?!a)", "", "a", 0, "1,1"),
    ("(?=)", "", "a", 0, "0,0"),
    ("(?!)", "", "a", 0, NO),
    // Lookbehind matches backwards.
    ("(?<=a)b", "", "bab", 0, "2,3"),
    ("(?<!a)b", "", "abb", 0, "2,3"),
    (r"(?<=(\d+)(\d+))$", "", "1053", 0, "4,4 0,1 1,4"),
    ("(?<=([ab]+)([bc]+))$", "", "abc", 0, "3,3 0,1 1,3"),
    (r"(?<=\1(a))b", "", "aab", 0, "2,3 1,2"),
    (r"(?<=(a)\1)b", "", "ab", 0, "1,2 0,1"),
    (r"(?<=(o)d\1)r", "", "hodor", 0, NO),
    (r"(?<=\1d(o))r", "", "hodor", 0, "4,5 3,4"),
    ("(?<=a(?=b))b", "", "ab", 0, "1,2"),
    (r"(?<=^|,)\w+", "", "ab,cd", 3, "3,5"),
    (r"(?<![a-z])\d+", "", "a12 34", 0, "2,3"),
    ("(?<=(?<!a)b)c", "", "abc bc", 0, "5,6"),
    (r"(?<=\$)\d+(?:\.\d+)?", "", "cost $42.50!", 0, "6,11"),
    ("(?<=a.c)d", "", "abcd", 0, "3,4"),
    ("(?<=a{2})b", "", "ab aab", 0, "5,6"),
    (r"(?<=(\w+))c", "", "abc", 0, "2,3 0,2"),
    (r"(?<=(\w+?))c", "", "abc", 0, "2,3 1,2"),
    ("(?<=ab|xb)c", "", "xbc", 0, "2,3"),
    ("(?<=(?:ab)+)c", "", "ababc", 0, "4,5"),
    ("(?<=(a|b)+)c", "", "abc", 0, "2,3 0,1"),
    ("(?<!(a))b", "", "cb", 0, "1,2 -"),
    ("(?<=a)", "", "a", 0, "1,1"),
    ("(?<=", "", "", 0, ERR),
    ("(?<", "", "", 0, ERR),
];
