//! Case-insensitive matching: `Canonicalize` without `u` (upper-casing of code units) and with
//! `u` (simple case folding), for literals, classes, ranges and backreferences.

use crate::common::{Case, NO};

pub const CASES: &[Case] = &[
    // ASCII.
    ("abc", "i", "xABC", 0, "1,4"),
    ("ABC", "i", "abc", 0, "0,3"),
    ("abc", "", "ABC", 0, NO),
    ("[a-c]+", "i", "xABCd", 0, "1,4"),
    ("[A-C]+", "i", "xabcd", 0, "1,4"),
    ("[^a-c]+", "i", "ABCdEF", 0, "3,6"),
    ("[W-c]+", "i", "wxyzAB", 0, "0,6"),
    (r"\w+", "i", "aB_9", 0, "0,4"),
    (r"(a)\1", "i", "aA", 0, "0,2 0,1"),
    (r"(A)\1", "i", "aa", 0, "0,2 0,1"),
    (r"(ab)\1", "i", "abAB", 0, "0,4 0,2"),
    (r"(ab)\1", "", "abAB", 0, NO),
    (r"(?<=\1(a))b", "i", "Aab", 0, "2,3 1,2"),
    ("a+?B", "i", "AAb", 0, "0,3"),
    // Latin-1 and beyond.
    ("\u{e9}", "i", "\u{c9}", 0, "0,1"),
    ("\u{c9}", "i", "\u{e9}", 0, "0,1"),
    ("[^\u{e9}]", "i", "\u{c9}", 0, NO),
    ("(\u{e9})\\1", "i", "\u{e9}\u{c9}", 0, "0,2 0,1"),
    ("\u{ff}", "i", "\u{178}", 0, "0,1"),
    ("\u{1c6}", "i", "\u{1c5}", 0, "0,1"),
    ("[\u{3b1}-\u{3c9}]+", "i", "\u{391}\u{392}\u{393}", 0, "0,3"),
    ("[\u{430}-\u{44f}]+", "i", "\u{41f}\u{420}\u{418}", 0, "0,3"),
    ("[\u{430}-\u{44f}]+", "iu", "\u{41f}\u{420}\u{418}", 0, "0,3"),
    // ß upper-cases to two characters, so without `u` it only matches itself; with `u` the
    // capital sharp s folds to it.
    ("\u{df}", "i", "\u{df}", 0, "0,1"),
    ("\u{df}", "i", "SS", 0, NO),
    ("\u{df}", "i", "\u{1e9e}", 0, NO),
    ("\u{df}", "iu", "\u{1e9e}", 0, "0,1"),
    ("\u{1e9e}", "iu", "\u{df}", 0, "0,1"),
    ("\u{df}", "iu", "ss", 0, NO),
    // Σ / σ / ς are one equivalence class in both modes.
    ("\u{3c3}", "i", "\u{3a3}", 0, "0,1"),
    ("\u{3c3}", "i", "\u{3c2}", 0, "0,1"),
    ("\u{3c2}", "i", "\u{3c3}", 0, "0,1"),
    ("\u{3a3}", "i", "\u{3c2}", 0, "0,1"),
    ("\u{3c3}", "iu", "\u{3c2}", 0, "0,1"),
    ("\u{3c2}", "iu", "\u{3a3}", 0, "0,1"),
    ("[\u{3c3}]", "i", "\u{3c2}", 0, "0,1"),
    ("[\u{3c3}-\u{3c9}]", "iu", "\u{3c2}", 0, "0,1"),
    ("(\u{3c3})\\1", "i", "\u{3c3}\u{3c2}", 0, "0,2 0,1"),
    ("(\u{3c3})\\1", "iu", "\u{3a3}\u{3c2}", 0, "0,2 0,1"),
    ("\u{3c3}", "", "\u{3c2}", 0, NO),
    // İ (U+0130) and ı (U+0131) are equivalent to nothing but themselves.
    ("i", "i", "\u{130}", 0, NO),
    ("\u{130}", "i", "i", 0, NO),
    ("\u{130}", "i", "\u{130}", 0, "0,1"),
    ("i", "iu", "\u{130}", 0, NO),
    ("\u{130}", "iu", "I", 0, NO),
    ("\u{131}", "i", "I", 0, NO),
    ("I", "i", "\u{131}", 0, NO),
    ("\u{131}", "iu", "I", 0, NO),
    ("\u{131}", "iu", "i", 0, NO),
    ("[a-z]+", "i", "\u{130}\u{131}", 0, NO),
    // A non-ASCII character never canonicalizes to an ASCII one without `u`; with `u`,
    // U+017F (long s) and U+212A (Kelvin) fold to `s` and `k`.
    ("s", "i", "\u{17f}", 0, NO),
    ("s", "iu", "\u{17f}", 0, "0,1"),
    ("k", "i", "\u{212a}", 0, NO),
    ("k", "iu", "\u{212a}", 0, "0,1"),
    ("\u{212a}", "iu", "k", 0, "0,1"),
    ("\u{212a}", "i", "K", 0, NO),
    ("[a-z]", "i", "\u{17f}", 0, NO),
    ("[a-z]", "iu", "\u{17f}", 0, "0,1"),
    ("[k-m]", "iu", "\u{212a}", 0, "0,1"),
    (r"\w", "i", "\u{212a}", 0, NO),
    (r"\w", "u", "\u{212a}", 0, NO),
    (r"\w", "iu", "\u{212a}", 0, "0,1"),
    (r"\w", "iu", "\u{17f}", 0, "0,1"),
    (r"\W", "iu", "S", 0, NO),
    (r"\W", "iu", "\u{17f}", 0, NO),
    (r"[^\W]", "iu", "\u{17f}", 0, "0,1"),
    (r"\b", "iu", "\u{17f}", 0, "0,0"),
    (r"\b", "i", "\u{17f}", 0, NO),
    (r"\b", "u", "\u{17f}", 0, NO),
    // µ (micro sign) and μ (Greek mu); Å and the Angstrom sign.
    ("\u{b5}", "i", "\u{3bc}", 0, "0,1"),
    ("\u{b5}", "iu", "\u{3bc}", 0, "0,1"),
    ("\u{e5}", "iu", "\u{212b}", 0, "0,1"),
    ("\u{e5}", "i", "\u{212b}", 0, NO),
    // Case pairs outside the BMP exist only with `u`.
    ("\u{10428}", "iu", "\u{10400}", 0, "0,2"),
    ("\u{10428}", "i", "\u{10400}", 0, NO),
    ("[\u{10428}-\u{1042f}]", "iu", "\u{10401}", 0, "0,2"),
    ("(\u{10428})\\1", "iu", "\u{10428}\u{10400}", 0, "0,4 0,2"),
];
